BEGIN;

CREATE SCHEMA blinkit;
SET search_path TO blinkit;

CREATE TABLE cities (
    city_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_name TEXT NOT NULL,
    state TEXT NOT NULL,
    UNIQUE (city_name, state)
);

CREATE TABLE categories (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name TEXT NOT NULL UNIQUE,
    is_perishable BOOLEAN NOT NULL
);

CREATE TABLE dark_stores (
    store_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_code TEXT NOT NULL UNIQUE,
    city_id INTEGER NOT NULL REFERENCES cities(city_id) ON DELETE RESTRICT,
    latitude NUMERIC(9,6) NOT NULL,
    longitude NUMERIC(9,6) NOT NULL,
    opened_on DATE NOT NULL,
    is_active BOOLEAN NOT NULL,
    max_daily_orders INTEGER NOT NULL,

    CHECK (latitude BETWEEN -90 AND 90),
    CHECK (longitude BETWEEN -180 AND 180),
    CHECK (max_daily_orders > 0)
);

CREATE TABLE products (
    product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku TEXT NOT NULL UNIQUE,
    product_name TEXT NOT NULL,
    brand TEXT NOT NULL,
    category_id INTEGER NOT NULL
        REFERENCES categories(category_id) ON DELETE RESTRICT,
    pack_size TEXT NOT NULL,
    mrp NUMERIC(12,2) NOT NULL,
    shelf_life_days INTEGER,
    is_active BOOLEAN NOT NULL,

    CHECK (mrp >= 0),
    CHECK (shelf_life_days > 0)
);

CREATE TABLE customers (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    phone TEXT NOT NULL UNIQUE,
    email TEXT UNIQUE,
    city_id INTEGER NOT NULL REFERENCES cities(city_id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE riders (
    rider_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    phone TEXT NOT NULL UNIQUE,
    store_id INTEGER NOT NULL
        REFERENCES dark_stores(store_id) ON DELETE RESTRICT,
    joined_on DATE NOT NULL,
    status TEXT NOT NULL,

    CHECK (length(trim(status)) > 0)
);

CREATE TABLE store_inventory (
    store_id INTEGER NOT NULL
        REFERENCES dark_stores(store_id) ON DELETE RESTRICT,
    product_id INTEGER NOT NULL
        REFERENCES products(product_id) ON DELETE RESTRICT,
    quantity_on_hand INTEGER NOT NULL,
    reorder_level INTEGER NOT NULL,
    selling_price NUMERIC(12,2) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,

    PRIMARY KEY (store_id, product_id),
    CHECK (quantity_on_hand >= 0),
    CHECK (reorder_level >= 0),
    CHECK (selling_price >= 0)
);

CREATE TABLE orders (
    order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL
        REFERENCES customers(customer_id) ON DELETE RESTRICT,
    store_id INTEGER NOT NULL
        REFERENCES dark_stores(store_id) ON DELETE RESTRICT,
    rider_id INTEGER REFERENCES riders(rider_id) ON DELETE RESTRICT,
    placed_at TIMESTAMPTZ NOT NULL,
    packed_at TIMESTAMPTZ,
    picked_up_at TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    promised_minutes INTEGER NOT NULL,
    subtotal NUMERIC(12,2) NOT NULL,
    delivery_fee NUMERIC(12,2) NOT NULL,
    handling_fee NUMERIC(12,2) NOT NULL,
    small_cart_fee NUMERIC(12,2) NOT NULL,
    total_amount NUMERIC(12,2) NOT NULL,
    payment_method TEXT NOT NULL,
    status TEXT NOT NULL,

    CHECK (promised_minutes > 0),
    CHECK (subtotal >= 0),
    CHECK (delivery_fee >= 0),
    CHECK (handling_fee >= 0),
    CHECK (small_cart_fee >= 0),
    CHECK (
        total_amount =
        subtotal + delivery_fee + handling_fee + small_cart_fee
    ),
    CHECK (packed_at IS NULL OR packed_at >= placed_at),
    CHECK (
        picked_up_at IS NULL OR
        (
            packed_at IS NOT NULL
            AND picked_up_at >= packed_at
        )
    ),
    CHECK (
        delivered_at IS NULL OR
        (
            picked_up_at IS NOT NULL
            AND delivered_at >= picked_up_at
        )
    ),
    CHECK (length(trim(payment_method)) > 0),
    CHECK (length(trim(status)) > 0)
);

CREATE TABLE order_items (
    order_id INTEGER NOT NULL
        REFERENCES orders(order_id) ON DELETE RESTRICT,
    product_id INTEGER NOT NULL
        REFERENCES products(product_id) ON DELETE RESTRICT,
    quantity_ordered INTEGER NOT NULL,
    quantity_delivered INTEGER NOT NULL,
    unit_price NUMERIC(12,2) NOT NULL,
    substitute_product_id INTEGER
        REFERENCES products(product_id) ON DELETE RESTRICT,

    PRIMARY KEY (order_id, product_id),
    CHECK (quantity_ordered > 0),
    CHECK (quantity_delivered >= 0),
    CHECK (quantity_delivered <= quantity_ordered),
    CHECK (unit_price >= 0)
);

CREATE TABLE inventory_movements (
    movement_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id INTEGER NOT NULL,
    product_id INTEGER NOT NULL,
    movement_type TEXT NOT NULL,
    quantity INTEGER NOT NULL,
    moved_at TIMESTAMPTZ NOT NULL,

    FOREIGN KEY (store_id, product_id)
        REFERENCES store_inventory(store_id, product_id)
        ON DELETE RESTRICT,

    CHECK (
        movement_type IN ('RESTOCK', 'DAMAGE', 'EXPIRY', 'ADJUSTMENT')
    ),
    CHECK (
        (movement_type = 'RESTOCK' AND quantity > 0)
        OR
        (movement_type IN ('DAMAGE', 'EXPIRY') AND quantity < 0)
        OR
        movement_type = 'ADJUSTMENT'
    )
);

COMMIT;